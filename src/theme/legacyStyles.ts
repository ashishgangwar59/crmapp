// Shared StyleSheet used by the CRM module screens (moved out of AppNavigator.tsx so screen files can import it).
import { StyleSheet, Platform, Appearance } from 'react-native';
import { colors, spacing, borderRadius, setForcedScheme } from './colors';
import { useAuthStore } from '../services/authStore';

export const createDynamicStyleSheet = <T extends Record<string, any>>(styleBuilder: () => T): any => {
  let lightCache: any = null;
  let darkCache: any = null;

  return new Proxy({}, {
    get(target, prop) {
      const themeMode = useAuthStore.getState().themeMode || 'system';
      const isDark = themeMode === 'system' ? Appearance.getColorScheme() === 'dark' : themeMode === 'dark';
      if (isDark) {
        if (!darkCache) {
          setForcedScheme('dark');
          try {
            darkCache = StyleSheet.create(styleBuilder() as any);
          } finally {
            setForcedScheme(null);
          }
        }
        return darkCache[prop as string] || {};
      } else {
        if (!lightCache) {
          setForcedScheme('light');
          try {
            lightCache = StyleSheet.create(styleBuilder() as any);
          } finally {
            setForcedScheme(null);
          }
        }
        return lightCache[prop as string] || {};
      }
    }
  }) as any;
};

